//! Focused-window tracking on KDE Plasma Wayland (SPEC §6.3): a KWin script reports the active window by calling
//! back into a D-Bus object served by the agent.
//!
//! The D-Bus connection runs on zbus' own executor thread, so there is no extra thread: the handle owns the
//! connection and, on drop, unloads the script, releases the bus name and deletes the script file.

use std::path::{Path, PathBuf};
use std::sync::Mutex;

use zbus::blocking::{Connection, Proxy};

use super::focus_linux::{make_app, Callback, Emitter};
use crate::{FocusHandle, FocusedApp, PlatformError, Result};

const OBJECT_PATH: &str = "/Focus";
const IFACE: &str = "dev.notideck.Focus";
const KWIN: &str = "org.kde.KWin";
const SCRIPTING_PATH: &str = "/Scripting";
const SCRIPTING_IFACE: &str = "org.kde.kwin.Scripting";
const SCRIPT_IFACE: &str = "org.kde.kwin.Script";

fn err(e: impl std::fmt::Display) -> PlatformError {
    PlatformError::Other(format!("kwin focus: {e}"))
}

/// Well-known bus name the KWin script calls back on.
fn bus_name(pid: u32) -> String {
    format!("dev.notideck.Focus.p{pid}")
}

/// KWin script plugin name (also its id for `unloadScript` / `isScriptLoaded`).
fn plugin_name(pid: u32) -> String {
    format!("notideck-focus-{pid}")
}

/// Maps the `Activated` arguments to a `FocusedApp` (pid <= 0 = unknown).
fn app_from_args(proc_root: &Path, class: String, caption: String, pid: i32) -> FocusedApp {
    make_app(proc_root, class, caption, u32::try_from(pid).ok().filter(|p| *p > 0))
}

/// The KWin script (Plasma 6 API): reports the active window at load, on activation and on caption change.
fn script_text(bus: &str) -> String {
    let bus = serde_json::to_string(bus).expect("string serializes");
    let path = serde_json::to_string(OBJECT_PATH).expect("string serializes");
    let iface = serde_json::to_string(IFACE).expect("string serializes");
    format!(
        r#"// Generated by Notideck: reports the focused window to the agent.
(function () {{
    var BUS = {bus};
    var tracked = null;
    function send(w) {{
        if (!w) {{
            callDBus(BUS, {path}, {iface}, "Cleared");
            return;
        }}
        callDBus(BUS, {path}, {iface}, "Activated", String(w.resourceClass || ""), String(w.caption || ""), (w.pid | 0));
    }}
    function onCaption() {{
        if (tracked && tracked === workspace.activeWindow) {{
            send(tracked);
        }}
    }}
    function track(w) {{
        if (tracked && tracked.captionChanged) {{
            try {{ tracked.captionChanged.disconnect(onCaption); }} catch (e) {{}}
        }}
        tracked = w;
        if (w && w.captionChanged) {{
            w.captionChanged.connect(onCaption);
        }}
        send(w);
    }}
    workspace.windowActivated.connect(track);
    track(workspace.activeWindow);
}})();
"#
    )
}

/// The D-Bus object the script calls.
struct FocusService {
    proc_root: PathBuf,
    emitter: Mutex<Emitter>,
}

#[zbus::interface(name = "dev.notideck.Focus")]
impl FocusService {
    fn activated(&self, resource_class: String, caption: String, pid: i32) {
        let app = app_from_args(&self.proc_root, resource_class, caption, pid);
        if let Ok(mut em) = self.emitter.lock() {
            em.emit(app);
        }
    }

    fn cleared(&self) {
        if let Ok(mut em) = self.emitter.lock() {
            em.emit(FocusedApp::default());
        }
    }
}

/// Unloads the script and releases the bus name on drop.
struct KwinGuard {
    conn: Connection,
    bus: String,
    plugin: String,
    file: PathBuf,
}

impl Drop for KwinGuard {
    fn drop(&mut self) {
        if let Err(e) = unload(&self.conn, &self.plugin) {
            tracing::warn!("kwin focus script unload failed: {e}");
        }
        let _ = self.conn.release_name(self.bus.as_str());
        let _ = std::fs::remove_file(&self.file);
    }
}

fn scripting(conn: &Connection) -> Result<Proxy<'static>> {
    Proxy::new(conn, KWIN, SCRIPTING_PATH, SCRIPTING_IFACE).map_err(err)
}

fn unload(conn: &Connection, plugin: &str) -> Result<bool> {
    scripting(conn)?.call("unloadScript", &(plugin,)).map_err(err)
}

/// Directory for the generated script: `$XDG_RUNTIME_DIR/notideck`, else the temp dir.
fn script_dir() -> PathBuf {
    match std::env::var("XDG_RUNTIME_DIR") {
        Ok(d) if !d.is_empty() => PathBuf::from(d).join("notideck"),
        _ => std::env::temp_dir().join("notideck"),
    }
}

/// Runs the loaded script: `/Scripting/Script<id>` (Plasma 6), falling back to `/<id>` (Plasma 5.2x).
fn run_script(conn: &Connection, id: i32) -> Result<()> {
    let mut last = None;
    for path in [format!("{SCRIPTING_PATH}/Script{id}"), format!("/{id}")] {
        let proxy = Proxy::new(conn, KWIN, path, SCRIPT_IFACE).map_err(err)?;
        match proxy.call::<_, _, ()>("run", &()) {
            Ok(()) => return Ok(()),
            Err(e) => last = Some(e),
        }
    }
    Err(err(format!("run script {id}: {}", last.expect("two attempts made"))))
}

pub fn start(proc_root: PathBuf, cb: Callback) -> Result<FocusHandle> {
    let pid = std::process::id();
    let (bus, plugin) = (bus_name(pid), plugin_name(pid));
    let service = FocusService { proc_root, emitter: Mutex::new(Emitter::new(cb)) };
    let conn = zbus::blocking::connection::Builder::session()
        .and_then(|b| b.name(bus.clone()))
        .and_then(|b| b.serve_at(OBJECT_PATH, service))
        .and_then(|b| b.build())
        .map_err(|e| err(format!("session bus: {e}")))?;

    let dir = script_dir();
    std::fs::create_dir_all(&dir)?;
    let file = dir.join(format!("kwin-focus-{pid}.js"));
    std::fs::write(&file, script_text(&bus))?;
    // From here the guard cleans up on any failure.
    let guard = KwinGuard { conn, bus, plugin: plugin.clone(), file: file.clone() };

    let scripting = scripting(&guard.conn).map_err(|e| err(format!("KWin not reachable ({e})")))?;
    // A stale script of the same name (crashed earlier run with a recycled pid) would refuse to load.
    let _ = unload(&guard.conn, &plugin);
    let file_str = file.to_str().ok_or_else(|| err("script path is not UTF-8"))?;
    let id: i32 =
        scripting.call("loadScript", &(file_str, plugin.as_str())).map_err(|e| err(format!("loadScript: {e}")))?;
    if id < 0 {
        return Err(err("KWin refused to load the focus script"));
    }
    run_script(&guard.conn, id)?;
    Ok(FocusHandle(Box::new(guard)))
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::sync::mpsc;
    use std::time::Duration;

    #[test]
    fn names_use_pid() {
        assert_eq!(bus_name(42), "dev.notideck.Focus.p42");
        assert_eq!(plugin_name(42), "notideck-focus-42");
    }

    #[test]
    fn script_mentions_bus_and_methods() {
        let s = script_text("dev.notideck.Focus.p42");
        for needle in [
            "\"dev.notideck.Focus.p42\"",
            "\"/Focus\"",
            "\"dev.notideck.Focus\"",
            "\"Activated\"",
            "\"Cleared\"",
            "windowActivated",
            "captionChanged",
            "resourceClass",
            "workspace.activeWindow",
        ] {
            assert!(s.contains(needle), "script lacks {needle}");
        }
    }

    #[test]
    fn args_map_to_app() {
        let dir = std::env::temp_dir().join(format!("nd-focus-kwin-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        std::fs::create_dir_all(dir.join("9")).unwrap();
        std::fs::write(dir.join("9/comm"), "firefox\n").unwrap();
        let a = app_from_args(&dir, "firefox".into(), "Tab".into(), 9);
        assert_eq!(
            (a.class.as_str(), a.title.as_str(), a.process.as_str(), a.pid),
            ("firefox", "Tab", "firefox", Some(9))
        );
        let b = app_from_args(&dir, "x".into(), "y".into(), 0);
        assert_eq!((b.pid, b.process.as_str()), (None, ""));
        assert_eq!(app_from_args(&dir, String::new(), String::new(), -3).pid, None);
    }

    /// Live check against the running KWin: `cargo test -p nd-platform kwin_live -- --ignored --nocapture`.
    #[test]
    #[ignore]
    fn kwin_live() {
        let (tx, rx) = mpsc::channel();
        let handle = start(PathBuf::from("/proc"), Box::new(move |a| tx.send(a).unwrap())).expect("start");
        let first = rx.recv_timeout(Duration::from_secs(5)).expect("initial event");
        println!("focus event: {first:?}");
        let end = std::time::Instant::now() + Duration::from_secs(10);
        let mut n = 1;
        while n < 3 {
            let left = end.saturating_duration_since(std::time::Instant::now());
            match rx.recv_timeout(left) {
                Ok(a) => {
                    n += 1;
                    println!("focus event: {a:?}");
                }
                Err(_) => break,
            }
        }
        println!("plugin: {}", plugin_name(std::process::id()));
        drop(handle);
    }
}
